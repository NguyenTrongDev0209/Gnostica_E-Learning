export const getCourseDetailById = (id) => {
  const numericId = Number(id);
  const baseCourse = courseCatalogMock.find((course) => course.id === numericId) || courseCatalogMock[0];
  const override = courseDetailOverrides[baseCourse.id] || {};

  return {
    ...baseCourse,
    ...defaultCourseDetail,
    ...override,
    instructor: {
      ...baseCourse.instructor,
      ...defaultCourseDetail.instructor,
      ...override.instructor,
    },
  };
};

export const searchCourses = (query) => {
  const normalized = (query || "").trim().toLowerCase();
  if (!normalized) return courseCatalogMock;

  return courseCatalogMock.filter((course) => {
    const haystack = `${course.title} ${course.category} ${course.instructor.name}`.toLowerCase();
    return haystack.includes(normalized);
  });
};
